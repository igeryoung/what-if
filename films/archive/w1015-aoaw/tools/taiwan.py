"""Builds taiwan.ts from Natural Earth 10m admin-0 (public domain): SVG path + per-row extents for the sweep.
usage: python -I taiwan.py ne_10m_admin_0_countries.geojson out.ts"""
import json, math, sys

KEEP = [0, 1, 3, 4, 5, 6, 7]  # main island, Lanyu, Penghu (3), Green Island, Waisanding; drops Kinmen (off-frame)
TOP, HEIGHT, CX = 960.0, 660.0, 540.0
d = json.load(open(sys.argv[1]))
tw = next(f for f in d['features'] if f['properties'].get('ADMIN') == 'Taiwan')
polys = [tw['geometry']['coordinates'][i][0] for i in KEEP]
main = polys[0]
lat_max = max(c[1] for c in main); lat_min = min(c[1] for c in main)
lon_c = (max(c[0] for c in main) + min(c[0] for c in main)) / 2
k = HEIGHT / (lat_max - lat_min)
kx = k * math.cos(math.radians((lat_max + lat_min) / 2))
P = lambda lon, lat: (CX + (lon - lon_c) * kx, TOP + (lat_max - lat) * k)

rings = [[P(*c) for c in ring] for ring in polys]
path = ''.join('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in r) + 'Z' for r in rings)


def chords(ring, y):
    xs = []
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        if (y1 <= y < y2) or (y2 <= y < y1):
            xs.append(x1 + (y - y1) * (x2 - x1) / (y2 - y1))
    xs.sort()
    return list(zip(xs[0::2], xs[1::2]))


STEP = 4
y0 = int(TOP)
rows, cum, total = [], [], 0.0
ys = list(range(y0, int(TOP + HEIGHT) + STEP, STEP))
for y in ys:
    yc = y + STEP / 2
    segs = chords(rings[0], yc)
    rows.append([round(segs[0][0], 1), round(segs[-1][1], 1)] if segs else [CX, CX])
    w = sum(b - a for r in rings for a, b in chords(r, yc))
    total += w * STEP
    cum.append(total)
cum = [round(c / total, 4) for c in cum]

# sanity: planar area of all rings in km^2 (equirectangular around each ring's latitude)
def area_km2(ring):
    R = 6371.0
    a = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        a += math.radians(x2 - x1) * (2 + math.sin(math.radians(y1)) + math.sin(math.radians(y2)))
    return abs(a) * R * R / 2

area = sum(area_km2(r) for r in polys)
north = min(rings[0], key=lambda p: p[1]); south = max(rings[0], key=lambda p: p[1])
start = P(121.56, 25.14)  # robot start: just inland of the north tip
with open(sys.argv[2], 'w') as o:
    o.write('// Generated by tools/taiwan.py from Natural Earth 10m admin-0 (public domain). Do not edit by hand.\n')
    o.write(f'// Natural Earth polygon area (all kept rings): {area:.0f} km^2\n')
    o.write(f'export const TW_PATH = {json.dumps(path)};\n')
    o.write(f'export const TW_Y0 = {y0};\nexport const TW_STEP = {STEP};\n')
    o.write(f'export const TW_ROWS: [number, number][] = {json.dumps(rows)};\n')
    o.write(f'export const TW_CUM: number[] = {json.dumps(cum)};\n')
    o.write(f'export const TW_NORTH = {{x: {north[0]:.1f}, y: {north[1]:.1f}}};\n')
    o.write(f'export const TW_SOUTH = {{x: {south[0]:.1f}, y: {south[1]:.1f}}};\n')
    o.write(f'export const TW_START = {{x: {start[0]:.1f}, y: {start[1]:.1f}}};\n')
    o.write(f'export const TW_KM_PER_PX = {111.32 / k:.4f};\n')
print('area', round(area), 'km2; north', north, 'south', south, 'km/px', 111.32 / k, 'x range', min(p[0] for p in rings[0]), max(p[0] for p in rings[0]))
